// The security posture, mapped to a standard control by control.
//
// contracts/baseline/security_posture.txt already records what the
// framework EMITS. This file answers the question that record cannot:
// which named requirements those values satisfy, and which ones the
// framework leaves to the application. "ASVS L2 verified" is only a
// checkable claim if each control has a test that fails when the control
// stops holding — otherwise it is a sentence in a README, which is the
// failure mode of every hand-written security checklist.
//
// Each row cites OWASP ASVS 4.0.3 and carries a probe. The probe decides
// the verdict; the frozen file records it. Three verdicts:
//
//	met           the framework satisfies it, and this probe exercised it
//	application   the framework provides the mechanism; the application
//	              must use it, and the note says how
//	not-met       the framework does not satisfy it, with the reason
//
// A "not-met" row is not a failure of this file. It is the point: a
// posture document that cannot say no is a marketing page.
